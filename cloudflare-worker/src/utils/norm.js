export function norm(s) {
  if (s == null) return "";
  let out = "";
  for (const ch of String(s)) {
    out += NFKC_MAP[ch] ?? ch;
  }
  return out
    .replace(/\u200b/g, "")
    .replace(/\ufeff/g, "")
    .replace(/\s+/g, " ")
    .trim();
}
